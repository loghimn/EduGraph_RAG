package fu.coreservice.service;

import fu.coreservice.dto.activitylog.ActivityLogFilter;
import fu.coreservice.entity.*;
import fu.coreservice.exception.AppException;
import fu.coreservice.exception.ErrorCode;
import fu.coreservice.repository.ActivityLogRepository;
import fu.coreservice.repository.UserRepository;
import fu.coreservice.service.impl.ActivityLogServiceImpl;
import org.hibernate.SessionFactory;
import org.hibernate.cfg.Configuration;
import org.junit.jupiter.api.*;
import org.springframework.aop.framework.ProxyFactory;
import org.springframework.data.jpa.repository.support.JpaRepositoryFactory;
import org.springframework.orm.jpa.JpaTransactionManager;
import org.springframework.orm.jpa.SharedEntityManagerCreator;
import org.springframework.transaction.annotation.AnnotationTransactionAttributeSource;
import org.springframework.transaction.interceptor.TransactionInterceptor;

import java.time.LocalDateTime;
import java.util.ArrayList;
import java.util.List;
import java.util.UUID;

import static org.assertj.core.api.Assertions.*;

class ActivityLogQueryServiceTest {
    private SessionFactory factory;
    private ActivityLogService service;
    private Long actorId;
    private final List<Long> ids = new ArrayList<>();
    private final LocalDateTime base = LocalDateTime.of(2026, 11, 10, 0, 0);

    @BeforeEach
    void setup() {
        factory = new Configuration().addAnnotatedClass(User.class).addAnnotatedClass(ActivityLog.class)
                .setProperty("hibernate.connection.driver_class", "org.h2.Driver")
                .setProperty("hibernate.connection.url", "jdbc:h2:mem:" + UUID.randomUUID() + ";MODE=PostgreSQL")
                .setProperty("hibernate.hbm2ddl.auto", "create-drop")
                .setProperty("hibernate.hbm2ddl.halt_on_error", "true")
                .setProperty("hibernate.generate_statistics", "true").buildSessionFactory();
        factory.inTransaction(session -> {
            User actor = User.builder().email("private@test.local").username("actor")
                    .passwordHash("private-hash").role(UserRole.STUDENT).passwordResetOtpHash("private-otp").build();
            User other = User.builder().email("other@test.local").username("other")
                    .passwordHash("test").role(UserRole.STUDENT).build();
            session.persist(actor);
            session.persist(other);
            actorId = actor.getUserId();
            for (int i = 0; i < 5; i++) {
                User user = i == 0 || i == 3 ? null : i == 2 ? other : actor;
                ActivityLog entry = ActivityLog.builder().actor(user)
                        .actorType(user == null ? ActivityActorType.SYSTEM : ActivityActorType.USER)
                        .action(i == 0 || i == 3 ? "SYSTEM_FAILURE_LIMIT" : i == 4 ? "DOCUMENT_CANCEL" : "ACCESS_DENIED")
                        .resourceType("DOCUMENT").status(i == 4 ? ActivityLogStatus.SUCCESS : ActivityLogStatus.FAILED)
                        .errorCode(i == 4 ? null : "TEST_ERROR").message("Safe summary").durationMs(50L).build();
                session.persist(entry);
                session.flush();
                ids.add(entry.getLogId());
                // CreationTimestamp is generated by Hibernate; set deterministic query boundaries explicitly.
                session.createMutationQuery("update ActivityLog set createdAt = :at where logId = :id")
                        .setParameter("at", base.plusHours(i == 2 ? 1 : i == 3 ? 2 : i == 4 ? 3 : i))
                        .setParameter("id", entry.getLogId()).executeUpdate();
            }
        });
        var repositories = new JpaRepositoryFactory(SharedEntityManagerCreator.createSharedEntityManager(factory));
        var manager = new JpaTransactionManager(factory);
        var proxy = new ProxyFactory(new ActivityLogServiceImpl(repositories.getRepository(ActivityLogRepository.class),
                repositories.getRepository(UserRepository.class), manager));
        proxy.setInterfaces(ActivityLogService.class);
        proxy.addAdvice(new TransactionInterceptor(manager, new AnnotationTransactionAttributeSource()));
        service = (ActivityLogService) proxy.getProxy();
    }

    @AfterEach
    void cleanup() { factory.close(); }

    @Test
    void paginatesWithStableNewestFirstOrderingIncludingTimestampTies() {
        var first = service.listLogs(filter(0, 2));
        assertThat(first.getContent()).extracting(item -> item.logId()).containsExactly(ids.get(4), ids.get(3));
        assertThat(first.getTotalElements()).isEqualTo(5);
        assertThat(first.getTotalPages()).isEqualTo(3);
        assertThat(first.isFirst()).isTrue();
        assertThat(first.isLast()).isFalse();
        var second = service.listLogs(filter(1, 2));
        assertThat(second.getContent()).extracting(item -> item.logId()).containsExactly(ids.get(2), ids.get(1));
        assertThat(service.listLogs(filter(2, 2)).isLast()).isTrue();
        var beyond = service.listLogs(filter(10, 2));
        assertThat(beyond.getContent()).isEmpty();
        assertThat(beyond.getTotalElements()).isEqualTo(5);
    }

    @Test
    void combinesAllFiltersAndUsesInclusiveFromExclusiveTo() {
        var result = service.listLogs(new ActivityLogFilter(0, 20, base.plusHours(1), base.plusHours(2),
                " access_denied ", ActivityLogStatus.FAILED, ActivityActorType.USER, actorId));
        assertThat(result.getContent()).singleElement().satisfies(item -> {
            assertThat(item.logId()).isEqualTo(ids.get(1));
            assertThat(item.createdAt()).isEqualTo(base.plusHours(1));
            assertThat(item.actorId()).isEqualTo(actorId);
            assertThat(item.actorUsername()).isEqualTo("actor");
        });
        assertThat(service.listLogs(new ActivityLogFilter(0, 20, null, base, null, null, null, null))
                .getContent()).isEmpty();
        assertThat(service.listLogs(new ActivityLogFilter(0, 20, base.plusHours(3), null, null, null, null, null))
                .getContent()).hasSize(1);
    }

    @Test
    void retainsAnonymousSystemLogsAndFetchesActorsWithoutPerRowQueries() {
        factory.getStatistics().clear();
        var page = service.listLogs(filter(0, 100));
        assertThat(page.getContent()).hasSize(5);
        assertThat(factory.getStatistics().getPrepareStatementCount()).isLessThanOrEqualTo(2L);
        var system = service.listLogs(new ActivityLogFilter(0, 20, null, null, null, null, ActivityActorType.SYSTEM, null));
        assertThat(system.getContent()).hasSize(2).allSatisfy(item -> {
            assertThat(item.actorId()).isNull();
            assertThat(item.actorUsername()).isNull();
        });
        assertThat(service.getLog(ids.get(0)).actorId()).isNull();
        assertThat(service.getLog(ids.get(1)).actorUsername()).isEqualTo("actor");
    }

    @Test
    void statusAndUnknownActionFiltersWorkAndReadDoesNotWriteLogs() {
        var success = service.listLogs(new ActivityLogFilter(0, 20, null, null, null, ActivityLogStatus.SUCCESS, null, null));
        assertThat(success.getContent()).extracting(item -> item.logId()).containsExactly(ids.get(4));
        assertThat(service.listLogs(new ActivityLogFilter(0, 20, null, null, "UNKNOWN_ACTION", null, null, null))
                .getContent()).isEmpty();
        service.getLog(ids.get(4));
        assertThat(service.listLogs(filter(0, 20)).getTotalElements()).isEqualTo(5);
    }

    @Test
    void validatesPagingActorTimeBoundsAndDetailIds() {
        for (var invalid : List.of(filter(-1, 20), filter(0, 0), filter(0, 101), filter(Integer.MAX_VALUE, 100),
                new ActivityLogFilter(0, 20, base, base, null, null, null, null),
                new ActivityLogFilter(0, 20, base.plusHours(1), base, null, null, null, null),
                new ActivityLogFilter(0, 20, null, null, null, null, null, 0L),
                new ActivityLogFilter(0, 20, null, null, "A".repeat(101), null, null, null))) {
            assertThatThrownBy(() -> service.listLogs(invalid)).isInstanceOfSatisfying(AppException.class,
                    ex -> assertThat(ex.getErrorCode()).isEqualTo(ErrorCode.INVALID_PARAMETER));
        }
        assertThatThrownBy(() -> service.getLog(0L)).isInstanceOfSatisfying(AppException.class,
                ex -> assertThat(ex.getErrorCode()).isEqualTo(ErrorCode.INVALID_PARAMETER));
        assertThatThrownBy(() -> service.getLog(Long.MAX_VALUE)).isInstanceOfSatisfying(AppException.class,
                ex -> assertThat(ex.getErrorCode()).isEqualTo(ErrorCode.ACTIVITY_LOG_NOT_FOUND));
    }

    private ActivityLogFilter filter(int page, int size) {
        return new ActivityLogFilter(page, size, null, null, null, null, null, null);
    }
}
